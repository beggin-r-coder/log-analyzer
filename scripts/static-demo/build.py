#!/usr/bin/env python3
"""Builds the browser-only demo in docs/ (served by GitHub Pages).

Run from the repository root:  python3 scripts/static-demo/build.py

It starts the real app once, signs in, saves the rendered dashboard and parser pages,
rewrites them for static hosting, copies the CSS/JS, and exports the generator, playbook
and classifier data from the compiled Java classes. docs/js/demo-backend.js (hand-written)
answers the API calls in the browser.
"""
import http.cookiejar
import os
import re
import secrets
import shutil
import socket
import subprocess
import sys
import tempfile
import time
import urllib.parse
import urllib.request

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
DOCS = os.path.join(ROOT, 'docs')
STATIC = os.path.join(ROOT, 'src', 'main', 'resources', 'static')
MVN = os.path.join(ROOT, 'mvnw')


def run(cmd, **kw):
    shown = ' '.join(cmd)
    print('+', shown if len(shown) < 160 else shown[:157] + '...')
    return subprocess.run(cmd, cwd=ROOT, check=True, **kw)


def free_port():
    with socket.socket() as s:
        s.bind(('127.0.0.1', 0))
        return s.getsockname()[1]


def export_data(tmp):
    cp_file = os.path.join(tmp, 'cp.txt')
    run(['sh', MVN, '-q', '-B', 'dependency:build-classpath', '-Dmdep.outputFile=' + cp_file])
    cp = os.path.join(ROOT, 'target', 'classes') + os.pathsep + open(cp_file).read().strip()
    run(['javac', '-d', tmp, '-cp', cp, os.path.join(ROOT, 'scripts', 'static-demo', 'ExportDemoData.java')])
    out = subprocess.run(['java', '-cp', cp + os.pathsep + tmp, 'ExportDemoData'], cwd=ROOT, check=True,
                         capture_output=True, text=True).stdout.strip()
    with open(os.path.join(DOCS, 'js', 'demo-data.js'), 'w') as f:
        f.write('/* Generated by scripts/static-demo/build.py from the Java classes. Do not edit. */\n')
        f.write('window.DEMO_DATA = ' + out + ';\n')


def fetch_pages(tmp):
    jar = sorted(f for f in os.listdir(os.path.join(ROOT, 'target')) if f.endswith('.jar'))[0]
    port, password = free_port(), secrets.token_urlsafe(12)
    env = dict(os.environ, PORT=str(port), APP_PASSWORD=password, DEMO_MODE='true', H2_CONSOLE_ENABLED='false',
               SIMULATOR_ENABLED='false', AI_ENABLED='false', DATA_DIR=os.path.join(tmp, 'data'))
    proc = subprocess.Popen(['java', '-jar', os.path.join(ROOT, 'target', jar)], cwd=ROOT, env=env,
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    base = 'http://127.0.0.1:%d' % port
    opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()),
                                         urllib.request.ProxyHandler({}))
    try:
        for _ in range(120):
            try:
                if opener.open(base + '/actuator/health', timeout=2).status == 200:
                    break
            except Exception:
                time.sleep(1)
        login = opener.open(base + '/login').read().decode()
        token = re.search(r'name="_csrf" value="([^"]+)"', login).group(1)
        form = urllib.parse.urlencode({'username': 'admin', 'password': password, '_csrf': token}).encode()
        opener.open(base + '/login', data=form)
        return {name: opener.open(base + path).read().decode() for name, path in (('index', '/'), ('parser', '/parser'))}
    finally:
        proc.terminate()
        proc.wait(timeout=30)


def to_static(html, page):
    # fingerprinted asset URLs -> plain relative paths
    html = re.sub(r'(href|src)="/(css|js)/([\w.]+?)(?:-[0-9a-f]{32})?\.(css|js)"', r'\1="\2/\3.\4"', html)
    html = re.sub(r'href="/favicon(?:-[0-9a-f]{32})?\.svg"', 'href="favicon.svg"', html)
    # libraries served from the site itself; the browser backend loads before any page script
    html = re.sub(r'<script src="https://cdn\.jsdelivr\.net/npm/chart\.js@[^"]+"></script>',
                  '<script src="vendor/chart.umd.min.js"></script>', html)
    backend = '<script src="js/demo-data.js"></script>\n\t<script src="js/demo-backend.js"></script>'
    html = re.sub(r'<script src="js/http\.js"></script>', '', html)
    html = html.replace('</title>', '</title>\n\t' + backend, 1)
    html = html.replace('<script src="js/report.js"></script>',
                        '<script>window.APP_PDF_LIBS = ["vendor/jspdf.umd.min.js", "vendor/jspdf.plugin.autotable.min.js"];</script>\n'
                        '\t<script src="js/report.js"></script>')
    # no login on a static site
    html = re.sub(r'<div class="menu-sep"></div>\s*<form action="/logout".*?</form>', '', html, flags=re.S)
    html = re.sub(r'<form [^>]*action="/logout".*?</form>', '', html, flags=re.S)
    html = re.sub(r'<input type="hidden" name="_csrf"[^>]*>', '', html)
    # links
    for a, b in (('href="/"', 'href="./"'), ('href="/parser"', 'href="parser.html"'), ('href="/#explorer"', 'href="./#explorer"'),
                 ('href="/#live"', 'href="./#live"')):
        html = html.replace(a, b)
    # honest wording for the browser-only copy
    for a, b in (
        ('Live analysis of logs persisted in H2 from', 'Live analysis of logs from'),
        ('banking services: errors, trends and incidents.', 'simulated banking services. This demo runs entirely in your browser.'),
        ('Everything here is live: logs stream from H2 every 2 seconds.', 'Everything runs in your browser: simulated bank logs stream in every 2 seconds.'),
        ('Newest first, pushed from H2 the instant a log is stored', 'Newest first, streamed as each log is generated'),
        ('Log Analyzer · Spring Boot + H2', 'Log Analyzer · browser demo (the full app runs on Spring Boot + H2)'),
        ('Parse &amp; store in H2', 'Parse &amp; store'),
        ('Stored ${data.events} events in H2. They now appear on the dashboard.', 'Stored ${data.events} events in this browser. They now appear on the dashboard.'),
    ):
        html = html.replace(a, b)
    html = re.sub(r'<p class="card-sub" style="margin-top:14px">API: .*?</p>', '', html, flags=re.S)
    return '<!-- Generated by scripts/static-demo/build.py. Edit the app, then rebuild. -->\n' + html


def main():
    if '--skip-build' not in sys.argv:
        run(['sh', MVN, '-q', '-B', 'package', '-DskipTests'])
    os.makedirs(os.path.join(DOCS, 'js'), exist_ok=True)
    os.makedirs(os.path.join(DOCS, 'css'), exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        export_data(tmp)
        pages = fetch_pages(tmp)
    for name, html in pages.items():
        with open(os.path.join(DOCS, name + '.html'), 'w') as f:
            f.write(to_static(html, name))
    shutil.copy(os.path.join(STATIC, 'css', 'dashboard.css'), os.path.join(DOCS, 'css'))
    for js in ('dashboard.js', 'ai.js', 'report.js', 'theme.js'):
        shutil.copy(os.path.join(STATIC, 'js', js), os.path.join(DOCS, 'js'))
    shutil.copy(os.path.join(STATIC, 'favicon.svg'), DOCS)
    open(os.path.join(DOCS, '.nojekyll'), 'w').close()
    print('Static demo written to', DOCS)


if __name__ == '__main__':
    main()
